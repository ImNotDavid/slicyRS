"""The two storage boundaries (A.9). Nothing outside this package knows how records or files are kept, so moving to Postgres
or object storage means adding an implementation here and naming it in the environment (DB_BACKEND, FILE_BACKEND).

Database: JSON documents grouped in named collections, a rate limiter, and the work queue. Every method is atomic.
Files: one area of files per record, addressed by (namespace, key) such as ("jobs", job_id). External tools (the slicer)
need real paths, so `path`/`workdir` return local paths; a remote backend keeps a local cache behind them and uploads in
`publish`, which callers invoke after something outside the interface (the slicer) has written into an area.
"""
from pathlib import Path
from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class Collection(Protocol):
    def all(self) -> list[dict[str, Any]]: ...          # in insertion order
    def get(self, key: str) -> dict[str, Any] | None: ...
    def put(self, key: str, value: dict[str, Any]) -> dict[str, Any]: ...
    def update(self, key: str, **fields: Any) -> dict[str, Any] | None: ...   # read-modify-write, atomic
    def delete(self, key: str) -> bool: ...


@runtime_checkable
class TaskStore(Protocol):
    """Work queue with leases: a claimed task that is not heartbeated goes back to a worker, up to max_attempts."""
    def enqueue(self, kind: str, payload: dict[str, Any], max_attempts: int = 3) -> int: ...
    def claim(self, worker: str, lease_s: float, now: float) -> dict[str, Any] | None: ...
    def heartbeat(self, task_id: int, worker: str, lease_s: float, now: float) -> bool: ...
    def finish(self, task_id: int, worker: str, error: str | None, now: float) -> None: ...
    def reap_dead(self, now: float) -> list[dict[str, Any]]: ...
    def counts(self) -> dict[str, int]: ...
    def clear(self) -> None: ...


@runtime_checkable
class Database(Protocol):
    tasks: TaskStore

    def collection(self, name: str) -> Collection: ...
    def rate_hit(self, key: str, limit: int, window_s: int) -> bool: ...   # True if allowed (and counted)
    def rate_reset(self) -> None: ...
    def size_bytes(self) -> int: ...                                       # for the storage report


@runtime_checkable
class FileStore(Protocol):
    def create(self, ns: str, key: str) -> Path: ...                       # new empty area; returns its working directory
    def exists(self, ns: str, key: str) -> bool: ...
    def workdir(self, ns: str, key: str) -> Path: ...                      # local directory of the area, for tools that write files
    def path(self, ns: str, key: str, name: str) -> Path: ...              # local path of one file in the area
    def has(self, ns: str, key: str, name: str) -> bool: ...
    def names(self, ns: str, key: str) -> list[str]: ...
    def write_bytes(self, ns: str, key: str, name: str, data: bytes) -> None: ...
    def write_text(self, ns: str, key: str, name: str, text: str) -> None: ...
    def read_bytes(self, ns: str, key: str, name: str) -> bytes: ...
    def read_text(self, ns: str, key: str, name: str) -> str: ...
    def publish(self, ns: str, key: str) -> None: ...                      # upload what an outside tool wrote (no-op for local disk)
    def remove(self, ns: str, key: str) -> int: ...                        # delete the area; bytes freed
    def remove_subdir(self, ns: str, key: str, name: str) -> None: ...     # delete a sub-folder (scratch output)
    def size(self, ns: str, key: str) -> int: ...
    def total_bytes(self, ns: str) -> int: ...
    def free_bytes(self) -> int: ...                                       # room left for new uploads
    def total_free(self) -> tuple[int, int]: ...                           # (total, free) bytes of the underlying storage
